export interface RiskSummaryCounts {
  critical: number;
  high: number;
  medium: number;
  low: number;
  total: number;
}

/**
 * Calculates severity counts from the centralized dataset.
 */
export function getCentralizedRiskSummary(items: CentralizedRisk[] = centralizedRisks): RiskSummaryCounts {
  return {
    critical: items.filter((r) => r.severity === 'Critical').length,
    high: items.filter((r) => r.severity === 'High').length,
    medium: items.filter((r) => r.severity === 'Medium').length,
    low: items.filter((r) => r.severity === 'Low').length,
    total: items.length,
  };
}

